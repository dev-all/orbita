export const demoProducts: Product[] = entries.map(
  ([name, detail, category, artwork, price, tone, color, badge], index) => {
    const id = `BAZ-${String(index + 1).padStart(3, "0")}`;
    const onRequest = index === 8 || index === 12;
    return {
      id,
      slug: name
        .normalize("NFD")
        .replace(/[\u0300-\u036f]/g, "")
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "-")
        .replace(/-$/, ""),
      name,
      description: `${detail}. Una propuesta para disfrutar tu casa y compartir los pequeños momentos. Producto ilustrativo del catálogo de demostración: medidas, composición, precios y disponibilidad deben confirmarse antes de vender.`,
      category,
      artwork,
      tone,
      featured: [0, 2, 6, 13].includes(index),
      badge: badge ?? null,
      weightGrams: ["plates", "glass"].includes(artwork) ? 2400 : 850,
      widthCm: 38,
      heightCm: 18,
      depthCm: 28,
      variants: [
        {
          id: `${id}-01`,
          sku: `${id}-01`,
          label: detail,
          color,
          priceCents: price * 100,
          stock: onRequest ? 0 : index === 19 ? 0 : 8 + (index % 5),
          sourcing: onRequest ? "ON_REQUEST" : "STOCK",
          supplierConfirmed: onRequest,
          supplierAvailable: onRequest ? 5 : 0,
          leadDays: onRequest ? 7 : 2,
        },
        {
          id: `${id}-02`,
          sku: `${id}-02`,
          label: detail,
          color: ["Marfil", "Arena", "Natural"].includes(color)
            ? "Gris piedra"
            : "Marfil",
          priceCents: (price + 1500) * 100,
          stock: index === 19 ? 0 : 4,
          sourcing: "STOCK",
          supplierConfirmed: false,
          supplierAvailable: 0,
          leadDays: 2,
        },
      ],
    };
  },
);
